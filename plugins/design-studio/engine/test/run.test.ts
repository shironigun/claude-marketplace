test('inputs.hash covers the config, every tsconfig read and a theme entry outside the sources, with line endings normalised', () => {
  const root = tinyApp();
  writeTree(root, {
    'tsconfig.json': '{ "references": [{ "path": "./tsconfig.app.json" }] }',
    'tsconfig.app.json': '{ "compilerOptions": { "baseUrl": "." } }',
    'theme/outside.ts': 'export const theme = createTheme({ spacing: 4 });\n',
  });
  const cfg = cfgOf(root, { themeEntry: 'theme/outside.ts' });
  const hash = (c: AppConfig = cfg): string => runInventory({ appRootAbs: root, cfg: c, git: false }).registry.inputs.hash;
  const seen = [hash()];
  const changed = (what: string, h: string): void => { assert.ok(!seen.includes(h), `${what} did not change the hash`); seen.push(h); };
  changed('the config', hash({ ...cfg, exclude: [...cfg.exclude, '**/never/**'] }));
  writeTree(root, { 'tsconfig.json': '{ "references": [{ "path": "./tsconfig.app.json" }], "include": ["src"] }' });
  changed('tsconfig.json', hash());
  const app = '{\n  "compilerOptions": { "baseUrl": "src" }\n}\n';
  const theme = 'export const theme = createTheme({\n  spacing: 6,\n});\n';
  writeTree(root, { 'tsconfig.app.json': app });
  changed('a referenced tsconfig', hash());
  writeTree(root, { 'theme/outside.ts': theme });
  changed('the theme entry', hash());
  const crlf = (s: string): string => s.replace(/\n/g, '\r\n');
  writeTree(root, { 'tsconfig.app.json': crlf(app), 'theme/outside.ts': crlf(theme) });
  assert.equal(hash(), seen[seen.length - 1], 'CRLF line endings changed the hash');
});

