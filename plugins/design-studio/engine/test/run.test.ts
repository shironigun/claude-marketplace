test('an invalid registry is never written: the command prints the errors and the out path and exits 1', async () => {
  const root = tinyApp();
  const out = join(tmpDir(), 'inv');
  const err: string[] = [];
  // A digest that is not 40 hex characters makes inputs.hash fail its schema pattern.
  const fake = () => ({ update() { return this; }, digest: () => 'not-a-sha1' });
  let code = -1;
  await new Promise<void>((done, fail) => {
    withMocked(crypto, 'createHash', fake, () => {
      main(['inventory', '--app', root, '--out', out, '--no-git'], { out: () => {}, err: (s) => { err.push(s); } }).then((c) => { code = c; done(); }, fail);
    });
  });
  assert.equal(code, 1);
  assert.equal(err[0], `inventory: the registry failed schema validation; nothing was written to ${out}`);
  assert.ok(err.some((e) => e.includes('/inputs/hash must match pattern')), err.join('\n'));
  assert.ok(!existsSync(out), 'nothing is written');
});

