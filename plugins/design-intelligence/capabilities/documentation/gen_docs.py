#!/usr/bin/env python3
"""Design Intelligence — Documentation Generation (plugin capability, NOT a skill).

Composes documentation from a pipeline RUN RECORD (the outputs the existing
skills already produce: analysis + implementation_request + manifest + review).
It does NOT re-run or duplicate generation logic — it only formats evidence that
already exists. Every value carries its evidence tag
(CONFIRMED/INFERRED/ASSUMED/UNKNOWN/CONFLICT). Missing fields render as UNKNOWN;
nothing is invented.

It also writes the run record to <workspace>/runs/<id>.json so the
impact-analysis capability can index screen/artifact relationships. The workspace
is the org's local, git-ignored overlay (default ./.claude/design-intelligence in
the project you run from), so run records never land inside the plugin.

Usage:
  python3 gen_docs.py <run-record.json>                    # prints Markdown doc, saves run
  python3 gen_docs.py --workspace DIR <run-record.json>    # explicit overlay folder
  python3 gen_docs.py examples/orders-list-mobile.json     # fictional example record
"""
import sys, os, json


def take_workspace(argv):
    """Pop `--workspace DIR` from argv and return the org's local overlay folder.

    Order: --workspace DIR, then $DESIGN_INTELLIGENCE_HOME, then
    ./.claude/design-intelligence (git-ignored, in the project you run from).
    See _shared/config/org-design-system.md.
    """
    if "--workspace" in argv:
        i = argv.index("--workspace")
        if i + 1 >= len(argv):
            print("--workspace needs a directory"); sys.exit(2)
        path = argv[i + 1]
        del argv[i:i + 2]
        return os.path.abspath(path)
    env = os.environ.get("DESIGN_INTELLIGENCE_HOME")
    return os.path.abspath(env or os.path.join(os.getcwd(), ".claude", "design-intelligence"))


def g(d, *keys, default="UNKNOWN"):
    for k in keys:
        if isinstance(d, dict) and k in d and d[k] not in (None, "", [], {}):
            d = d[k]
        else:
            return default
    return d


def section(title, rows):
    """rows: either a list of bullet strings, or a list of (label, value) tuples."""
    out = [f"## {title}", ""]
    if not rows:
        out.append("_UNKNOWN — not present in the run record._\n"); return "\n".join(out)
    for row in rows:
        if isinstance(row, tuple):
            label, val = row
            if isinstance(val, list):
                out.append(f"**{label}:**")
                out += [f"- {v}" for v in val] or ["- UNKNOWN"]
            else:
                out.append(f"- **{label}:** {val}")
        else:
            out.append(f"- {row}")
    out.append("")
    return "\n".join(out)


def build(run):
    scr = g(run, "screen"); node = g(run, "figma_node")
    md = [f"# Design Implementation Documentation — {scr}", ""]
    md.append("_Generated by the Documentation capability from a pipeline run record. "
              "Values carry evidence tags; missing data is UNKNOWN (never invented)._\n")
    md.append(section("Source", [
        ("Screen name", scr),
        ("Figma source/node", node),
        ("Platform", g(run, "platform")),
        ("Dimensions", g(run, "dimensions")),
    ]))
    md.append(section("Component inventory & MUI mapping", g(run, "components", default=[]) if isinstance(g(run,"components",default=[]),list) else []))
    md.append(section("Design tokens used", g(run, "tokens", default=[]) if isinstance(g(run,"tokens",default=[]),list) else []))
    md.append(section("Typography", [("Typography", g(run, "typography"))]))
    md.append(section("States implemented", g(run, "states", default=[]) if isinstance(g(run,"states",default=[]),list) else []))
    md.append(section("Accessibility decisions", g(run, "accessibility", default=[]) if isinstance(g(run,"accessibility",default=[]),list) else []))
    md.append(section("Responsive behavior", [("Responsive", g(run, "responsive"))]))
    md.append(section("Design decisions", g(run, "design_decisions", default=[]) if isinstance(g(run,"design_decisions",default=[]),list) else []))
    md.append(section("Assumptions", g(run, "assumptions", default=[]) if isinstance(g(run,"assumptions",default=[]),list) else []))
    md.append(section("Unresolved values (UNKNOWN)", g(run, "unresolved", default=[]) if isinstance(g(run,"unresolved",default=[]),list) else []))
    md.append(section("Source conflicts (CONFLICT)", g(run, "conflicts", default=[]) if isinstance(g(run,"conflicts",default=[]),list) else []))
    md.append(section("Review findings", g(run, "review_findings", default=[]) if isinstance(g(run,"review_findings",default=[]),list) else []))
    md.append(section("Correction history", g(run, "corrections", default=[]) if isinstance(g(run,"corrections",default=[]),list) else []))
    md.append(section("Final review", [("Final verdict", g(run, "final_verdict"))]))
    return "\n".join(md)


def main():
    argv = sys.argv[1:]
    runs_dir = os.path.join(take_workspace(argv), "runs")
    if len(argv) < 1:
        print("usage: gen_docs.py [--workspace DIR] <run-record.json>"); sys.exit(2)
    run = json.load(open(argv[0], encoding="utf-8"))
    os.makedirs(runs_dir, exist_ok=True)
    rid = run.get("id") or os.path.splitext(os.path.basename(argv[0]))[0]
    out = os.path.join(runs_dir, rid + ".json")
    json.dump(run, open(out, "w", encoding="utf-8"), indent=2)
    print(f"run record saved to {out}", file=sys.stderr)
    print(build(run))


if __name__ == "__main__":
    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8")  # Windows consoles default to a legacy code page
    main()
